-- Run as PostgreSQL administrator in sales_rls_demo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.sales (
  sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_date DATE NOT NULL,
  product TEXT NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  region TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.manager_regions (
  login_role NAME PRIMARY KEY,
  region TEXT NOT NULL
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='regional_manager') THEN
    CREATE ROLE regional_manager NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='manager_west') THEN
    CREATE ROLE manager_west LOGIN PASSWORD 'ChangeMe_West_123!';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='manager_east') THEN
    CREATE ROLE manager_east LOGIN PASSWORD 'ChangeMe_East_123!';
  END IF;
END $$;

GRANT regional_manager TO manager_west, manager_east;

INSERT INTO public.sales(sale_date,product,amount,region) VALUES
('2026-10-01','Laptop',55000,'WEST'),
('2026-10-02','Keyboard',1800,'WEST'),
('2026-10-03','Monitor',12000,'EAST'),
('2026-10-04','Mouse',700,'EAST'),
('2026-10-05','Printer',9500,'NORTH'),
('2026-10-06','Tablet',22000,'SOUTH');

INSERT INTO public.manager_regions(login_role,region) VALUES
('manager_west','WEST'), ('manager_east','EAST')
ON CONFLICT(login_role) DO UPDATE SET region=EXCLUDED.region;

REVOKE ALL ON public.manager_regions FROM PUBLIC, regional_manager,
  manager_west, manager_east;
GRANT SELECT ON public.sales TO regional_manager;
REVOKE ALL ON public.sales FROM PUBLIC;

-- SECURITY DEFINER function reads the protected account-to-region mapping.
CREATE OR REPLACE FUNCTION public.current_manager_region()
RETURNS TEXT LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = pg_catalog
AS $$
  SELECT mr.region FROM public.manager_regions mr
  WHERE mr.login_role = session_user
$$;

ALTER FUNCTION public.current_manager_region() OWNER TO CURRENT_USER;
REVOKE ALL ON FUNCTION public.current_manager_region() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.current_manager_region() TO regional_manager;

ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS regional_sales_select ON public.sales;
CREATE POLICY regional_sales_select ON public.sales
FOR SELECT TO regional_manager
USING (region = public.current_manager_region());

COMMIT;
